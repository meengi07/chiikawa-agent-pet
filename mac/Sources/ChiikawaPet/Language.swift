import Foundation

enum AppLanguage: String, CaseIterable, Identifiable {
    case english = "en", korean = "ko"
    var id: String { rawValue }
    var title: String { self == .english ? "English" : "한국어" }
    var locale: Locale { Locale(identifier: self == .english ? "en_US" : "ko_KR") }
    static var current: AppLanguage {
        AppLanguage(rawValue: UserDefaults.standard.string(forKey: "appLanguage") ?? "en") ?? .english
    }
}

func T(_ text: String) -> String {
    if AppLanguage.current == .english { return EnglishText.translate(text) }
    if let exact = EnglishText.words.first(where: { $0.1 == text }) { return exact.0 }
    var translated = text
    for (korean, english) in EnglishText.words where english.count > 40 {
        translated = translated.replacingOccurrences(of: english, with: korean)
    }
    return translated
}

